export async function seedDatabase(): Promise<{
  services: number;
  fields: number;
  faqs: number;
  articles: number;
  created: boolean;
}> {
  const created = { services: 0, fields: 0, faqs: 0, articles: 0 };

  for (const s of SERVICES) {
    const existing = await get<{ id: string }>("SELECT id FROM services WHERE slug = ?", [s.slug]);
    if (!existing) {
      const id = newIdSafe();
      await run(
        `INSERT INTO services (id, slug, title, tagline, summary, intro_md, audience_md, process_md, documents_md,
          seo_title, seo_description, icon, featured, active, sort_order, allow_attachments, max_attachments,
          reviewed_at, created_at, updated_at)
         VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,1,?,?,?,?)`,
        [
          id, s.slug, s.title, s.tagline, s.summary, s.intro_md, s.audience_md, s.process_md, s.documents_md,
          s.seo_title, s.seo_description, s.icon, s.featured, 1, s.sort_order, s.max_attachments,
          null, nowIso(), nowIso(),
        ],
      );
      created.services++;
    }
  }

  for (const f of FIELDS) {
    const service = await get<{ id: string }>("SELECT id FROM services WHERE slug = ?", [f.service]);
    if (!service) continue;
    const exists = await get<{ id: string }>(
      "SELECT id FROM service_fields WHERE service_id = ? AND field_key = ?",
      [service.id, f.field_key],
    );
    if (exists) continue;
    const order = FIELDS.filter((x) => x.service === f.service).findIndex((x) => x.field_key === f.field_key) + 1;
    await run(
      `INSERT INTO service_fields (id, service_id, field_key, label, type, options_json, placeholder, help_text, required, sort_order, active)
       VALUES (?,?,?,?,?,?,?,?,?,?,1)`,
      [
        newIdSafe(), service.id, f.field_key, f.label, f.type, JSON.stringify(f.options || []),
        f.placeholder || "", f.help_text || "", f.required ? 1 : 0, order,
      ],
    );
    created.fields++;
  }

  const faqCount = await get<{ c: number }>("SELECT COUNT(*) AS c FROM faqs");
  if (!faqCount || Number(faqCount.c) === 0) {
    let order = 1;
    for (const f of FAQS) {
      let serviceId: string | null = null;
      if (f.service) {
        const svc = await get<{ id: string }>("SELECT id FROM services WHERE slug = ?", [f.service]);
        serviceId = svc ? svc.id : null;
      }
      await run(
        "INSERT INTO faqs (id, service_id, question, answer_md, sort_order, published, created_at, updated_at) VALUES (?,?,?,?,?,1,?,?)",
        [newIdSafe(), serviceId, f.question, f.answer, order++, nowIso(), nowIso()],
      );
      created.faqs++;
    }
  }

  // مقاله‌ها بر اساس slug درج می‌شوند تا پایگاه‌داده‌های قدیمی هم مقاله‌های جدید را دریافت کنند.
  // مقاله‌ای که از قبل وجود دارد دست‌نخورده می‌ماند.
  for (const a of ARTICLES) {
    const exists = await get<{ id: string }>("SELECT id FROM articles WHERE slug = ?", [a.slug]);
    if (exists) continue;
    await run(
      `INSERT INTO articles (id, slug, title, excerpt, body_md, cover_path, author, category, status,
         related_services, seo_title, seo_description, review_note, published_at, updated_at, created_at)
       VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)`,
      [
        newIdSafe(), a.slug, a.title, a.excerpt, a.body, "", "دفتر خدمات سلامت ۴۷۷", a.category, a.status,
        JSON.stringify(a.related), a.seo_title, a.seo_description, a.review_note || "",
        a.status === "published" ? nowIso() : null, nowIso(), nowIso(),
      ],
    );
    created.articles++;
  }

  // مقاله‌های آموزشی هر خدمت (دو مقاله برای هر خدمت، با تصویر کاور)
  for (const a of ARTICLE_PACK) {
    const exists = await get<{ id: string; cover_path: string }>("SELECT id, cover_path FROM articles WHERE slug = ?", [a.slug]);
    const cover = `/images/articles/${a.cover}`;
    if (exists) {
      // فقط تصویر کاور خالی را پر می‌کنیم؛ متن ویرایش‌شده توسط مدیر حفظ می‌شود
      if (!exists.cover_path) await run("UPDATE articles SET cover_path = ? WHERE id = ?", [cover, exists.id]);
      continue;
    }
    await run(
      `INSERT INTO articles (id, slug, title, excerpt, body_md, cover_path, author, category, status,
         related_services, seo_title, seo_description, review_note, published_at, updated_at, created_at)
       VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)`,
      [
        newIdSafe(), a.slug, a.title, a.excerpt, a.body, cover, "تیم محتوای دفتر خدمات سلامت ۴۷۷", a.category, "published",
        JSON.stringify(a.related), a.seo_title, a.seo_description,
        "مطلب آموزشی است. الزامات و مدارک نهایی هر خدمت پیش از اعلام رسمی توسط دفتر بازبینی می‌شود.",
        nowIso(), nowIso(), nowIso(),
      ],
    );
    created.articles++;
  }

  return { ...created, created: created.services > 0 };
}
